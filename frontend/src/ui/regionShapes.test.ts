import { describe, expect, it } from 'vitest';
import { REGION_IDS } from '../lib/regions';
import { REGION_SHAPE_VIEWBOX, REGION_SHAPES } from './regionShapes';

describe('region shapes (generated by scripts/region-icons.mjs)', () => {
  it('has a non-empty outline for every region but the world', () => {
    for (const id of REGION_IDS) {
      if (id === 'world') continue;
      const shape = REGION_SHAPES[id];
      expect(shape, id).toBeDefined();
      expect(shape.d.length, id).toBeGreaterThan(50);
      // closed subpaths of absolute moves/lines only
      expect(shape.d, id).toMatch(/^(M[\d. ]+(L[\d. ]+)+Z)+$/);
    }
  });

  it('keeps every point inside the viewBox', () => {
    const [, , w, h] = REGION_SHAPE_VIEWBOX.split(' ').map(Number);
    for (const shape of Object.values(REGION_SHAPES)) {
      const nums = `${shape.d}${shape.context ?? ''}`.match(/[\d.]+/g)!.map(Number);
      for (let i = 0; i < nums.length; i += 2) {
        expect(nums[i]).toBeGreaterThanOrEqual(0);
        expect(nums[i]).toBeLessThanOrEqual(w);
        expect(nums[i + 1]).toBeLessThanOrEqual(h);
      }
    }
  });
});

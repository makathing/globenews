export function lookupPlace(name: string): Place | undefined {
  return GAZETTEER[name.trim().toLowerCase()];
}

/** Snap agent coordinates to the gazetteer when the name matches but coords are far off. */
export function reconcileCoordinates(
  locationName: string,
  lat: number,
  lon: number,
): { lat: number; lon: number; cc?: string } {
  // Most specific part first: "Tokyo, Japan" should snap to Tokyo, not the country centroid.
  for (const part of locationName.split(/[,/]/).map((p) => p.trim())) {
    const place = lookupPlace(part);
    if (place) {
      const far = Math.abs(place.lat - lat) > 8 || Math.abs(place.lon - lon) > 8;
      return far ? { lat: place.lat, lon: place.lon, cc: place.cc } : { lat, lon, cc: place.cc };
    }
  }
  return { lat, lon };
}
